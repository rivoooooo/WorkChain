export function resolveLanguage(raw: string): Language {
  const normalized = raw.toLowerCase();
  if (normalized === 'zh' || normalized === 'zh-cn') return 'zh';
  return localeOptions.some((locale) => locale.code === normalized)
    ? (normalized as Language)
    : 'en';
}

export const localePath = (language: Language) =>
  localeOptions.find((locale) => locale.code === language)?.path || 'en';

export const isRtlLanguage = (language: Language) => language === 'ar';

